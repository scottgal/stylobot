/// <summary>
///     Summary statistics for dashboard overview.
///     Updated periodically and sent to clients.
/// </summary>
public sealed record DashboardSummary
{
    public required DateTime Timestamp { get; init; }
    public required int TotalRequests { get; init; }
    public required int BotRequests { get; init; }
    public required int HumanRequests { get; init; }
    public required int UncertainRequests { get; init; }

    public double BotPercentage => TotalRequests > 0
        ? (double)BotRequests / TotalRequests * 100
        : 0;

    public required Dictionary<string, int> RiskBandCounts { get; init; }
    public required Dictionary<string, int> TopBotTypes { get; init; }
    public required Dictionary<string, int> TopActions { get; init; }
    public double AverageProcessingTimeMs { get; init; }
    public double LastProcessingTimeMs { get; init; }
    public required int UniqueSignatures { get; init; }

    // Fingerprint-level counts derived from the signatures table (one row per
    // unique fingerprint, with EWMA-blended bot_probability + risk_band).
    // Distinct from BotRequests/HumanRequests which count individual detection rows.
    // Dashboards should prefer these for "how many actors did we see" displays;
    // BotRequests/HumanRequests are still correct for "how much traffic" displays.
    public int BotFingerprints { get; init; }
    public int HumanFingerprints { get; init; }
    public int HighRiskFingerprints { get; init; }

    // Traffic volume and latency aggregates — computed from the detections sub-query
    // and therefore subject to the same audience filter (when set).
    public long BytesOut { get; init; }
    // SQLite lacks PERCENTILE_CONT — approximation: avg + (max - avg) * 0.9.
    // Postgres backend returns true PERCENTILE_CONT.
    public double P95ProcessingTimeMs { get; init; }
    public double MaxProcessingTimeMs { get; init; }
}

